<?php

namespace utils\validators;

use Paprika\utils\validators\DateNaissanceValidator;
use Paprika\utils\validators\PasswordValidator;
use PHPUnit\Framework\TestCase;

class DateNaissanceValidatorTest extends TestCase
{
    private DateNaissanceValidator $validator;

    public static function setUpBeforeClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nInitializing PasswordValidator tests...\n");
    }
    public function setUp() : void {
        parent::setUp(); // TODO : change the autogenerated stub
        fwrite(STDOUT, __METHOD__ . "\nSetting up test...\n");
        $this->validator = new DateNaissanceValidator();
    }

    // ============ Tests valides ============
    public function testValidBirthDate1(): void
    {
        $result = $this->validator->validate('2008-06-15');
        $this->assertTrue($result, "Birth date '2008-06-15' (16 years old) should be valid");
    }

    public function testValidBirthDate2(): void
    {
        $result = $this->validator->validate('1990-03-22');
        $this->assertTrue($result, "Birth date '1990-03-22' (34 years old) should be valid");
    }

    public function testValidBirthDate3(): void
    {
        $result = $this->validator->validate('1959-12-10');
        $this->assertTrue($result, "Birth date '1959-12-10' (65 years old) should be valid");
    }

    public function testValidBirthDateMinimumAge(): void
    {
        // Date de naissance exactement 16 ans ago
        $date = (new \DateTime())->modify('-16 years')->format('Y-m-d');
        $result = $this->validator->validate($date);
        $this->assertTrue($result, "Birth date exactly 16 years ago should be valid");
    }

    public function testValidBirthDateMaximumAge(): void
    {
        // Date de naissance exactement 65 ans ago
        $date = (new \DateTime())->modify('-65 years')->format('Y-m-d');
        $result = $this->validator->validate($date);
        $this->assertTrue($result, "Birth date exactly 65 years ago should be valid");
    }

    // ============ Tests invalides - Âge ============
    public function testBirthDateTooYoung(): void
    {
        // Moins de 16 ans
        $date = (new \DateTime())->modify('-15 years')->format('Y-m-d');
        $result = $this->validator->validate($date);
        $this->assertFalse($result, "Birth date less than 16 years ago should fail");
    }

    public function testBirthDateTooOld(): void
    {
        // Plus de 65 ans
        $date = (new \DateTime())->modify('-66 years')->format('Y-m-d');
        $result = $this->validator->validate($date);
        $this->assertFalse($result, "Birth date more than 65 years ago should fail");
    }

    // ============ Tests invalides - Format ============
    public function testBirthDateInvalidFormat1(): void
    {
        $result = $this->validator->validate('15/06/2008');
        $this->assertFalse($result, "Birth date with format 'DD/MM/YYYY' should fail");
    }

    public function testBirthDateInvalidFormat2(): void
    {
        $result = $this->validator->validate('06-15-2008');
        $this->assertFalse($result, "Birth date with format 'MM-DD-YYYY' should fail");
    }

    public function testBirthDateInvalidFormat3(): void
    {
        $result = $this->validator->validate('2008/06/15');
        $this->assertFalse($result, "Birth date with format 'YYYY/MM/DD' should fail");
    }

    // ============ Tests invalides - Date invalide ============
    public function testBirthDateInvalidDay(): void
    {
        $result = $this->validator->validate('2008-06-31');
        $this->assertFalse($result, "Invalid day (31 in June) should fail");
    }

    public function testBirthDateInvalidMonth(): void
    {
        $result = $this->validator->validate('2008-13-15');
        $this->assertFalse($result, "Invalid month (13) should fail");
    }

    public function testBirthDateFutureDate(): void
    {
        $date = (new \DateTime())->modify('+1 day')->format('Y-m-d');
        $result = $this->validator->validate($date);
        $this->assertFalse($result, "Future date should fail");
    }

    // ============ Tests invalides - Chaîne vide ============
    public function testBirthDateEmpty(): void
    {
        $result = $this->validator->validate('');
        $this->assertFalse($result, "Empty birth date should fail");
    }

    public function testBirthDateNull(): void
    {
        $result = $this->validator->validate('null');
        $this->assertFalse($result, "String 'null' should fail");
    }

    // ============ Tests invalides - Format invalide ============
    public function testBirthDateWithTime(): void
    {
        $result = $this->validator->validate('2008-06-15 10:30:00');
        $this->assertFalse($result, "Birth date with time should fail");
    }

    public function testBirthDateGarbage(): void
    {
        $result = $this->validator->validate('not-a-date');
        $this->assertFalse($result, "Garbage string should fail");
    }

    public function teardown() : void {
        fwrite(STDOUT, __METHOD__ . "\nCleaning up after test...\n");
        parent::teardown();
    }

    public static function tearDownAfterClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nDONE!\n");
    }
}
