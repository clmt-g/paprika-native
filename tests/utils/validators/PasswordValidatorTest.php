<?php

namespace utils\validators;

use Paprika\utils\validators\PasswordValidator;
use PHPUnit\Framework\TestCase;

class PasswordValidatorTest extends TestCase
{
    private PasswordValidator $validator;

    public static function setUpBeforeClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nYES IT WORKS !!\n");
    }

    public function setUp() : void {
        parent::setUp(); // TODO : change the autogenerated stub
        $this->validator = new PasswordValidator();
    }

    public function check_PasswordWithLessThan12CharactersFail() : void {
        $result = $this->validator->validate('123+aze');
        $this->assertFalse($result, "The password must have 12 characters");
    }

    public function check_PasswordWithMoretah12CharactersPass() : void {
        $result = $this->validator->validate('');
        $this->assertTrue($result, "The password have 12 characters");
    }

    public function check_PasswordWithNoCapitalLettersFail() : void {
        $result = $this->validator->validate('');
        $this->assertFalse($result, "The password must have capital letters");
    }

    public function check_PasswordWithCapitalLettersPass() : void {
        $result = $this->validator->validate('');
        $this->assertTrue($result, "The password have capital letters");
    }

    public function teardown() : void {
        parent::teardown();
    }

    public static function tearDownAfterClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nDONE!\n");
    }
}
