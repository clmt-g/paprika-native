<?php

namespace utils\validators;

use Paprika\utils\validators\PasswordValidator;
use PHPUnit\Framework\TestCase;

class PasswordValidatorTest extends TestCase
{
    private PasswordValidator $validator;

    public static function setUpBeforeClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nInitializing PasswordValidator tests...\n");
    }

    public function setUp() : void {
        parent::setUp(); // TODO : change the autogenerated stub
        fwrite(STDOUT, __METHOD__ . "\nSetting up test...\n");
        $this->validator = new PasswordValidator();
    }

    // Tests valides
    public function testValidPassword1(): void
    {
        $result = $this->validator->validate('MyPassword123!');
        $this->assertTrue($result, "Password 'MyPassword123!' should be valid");
    }

    public function testValidPassword2(): void
    {
        $result = $this->validator->validate('SecurePass456@');
        $this->assertTrue($result, "Password 'SecurePass456@' should be valid");
    }

    public function testValidPassword3(): void
    {
        $result = $this->validator->validate('AnotherOne789#');
        $this->assertTrue($result, "Password 'AnotherOne789#' should be valid");
    }

    // Tests invalides
    public function testPasswordTooShort(): void
    {
        $result = $this->validator->validate('123+aze');
        $this->assertFalse($result, "Password with less than 12 characters should fail");
    }

    public function testPasswordNoUppercase(): void
    {
        $result = $this->validator->validate('mypassword123!');
        $this->assertFalse($result, "Password without uppercase letter should fail");
    }

    public function testPasswordNoLowercase(): void
    {
        $result = $this->validator->validate('MYPASSWORD123!');
        $this->assertFalse($result, "Password without lowercase letter should fail");
    }

    public function testPasswordNoNumber(): void
    {
        $result = $this->validator->validate('MyPassword!');
        $this->assertFalse($result, "Password without number should fail");
    }

    public function testPasswordNoSpecialChar(): void
    {
        $result = $this->validator->validate('MyPassword123');
        $this->assertFalse($result, "Password without special character should fail");
    }

    public function testPasswordEmpty(): void
    {
        $result = $this->validator->validate('');
        $this->assertFalse($result, "Empty password should fail");
    }

    public function teardown() : void {
        fwrite(STDOUT, __METHOD__ . "\nCleaning up after test...\n");
        parent::teardown();
    }

    public static function tearDownAfterClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nDONE!\n");
    }
}
