<?php

namespace utils;

use Paprika\utils\Filtre;
use Paprika\utils\validators\DateNaissanceValidator;
use Paprika\utils\validators\PasswordValidator;
use Paprika\utils\validators\GradeValidator;
use Paprika\utils\validators\MailValidator;
use Paprika\utils\validators\MatriculeValidator;
use Paprika\utils\validators\NameValidator;
use PHPUnit\Framework\TestCase;

class FiltreTest extends TestCase
{
    private Filtre $filtre;

    public static function setUpBeforeClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nInitializing PasswordValidator tests...\n");
    }
    public function setUp() : void {
        parent::setUp(); // TODO : change the autogenerated stub
        fwrite(STDOUT, __METHOD__ . "\nSetting up test...\n");
        $this->filtre = new Filtre();
    }

    // ========== TESTS D'INTEGRATION DE FILTRE ============

    // --- password ---
    public function testValidPassword(): void {
        $data = [
            'password' => 'MyPassword123!'
        ];
        $this->filtre->addValidator('password', new PasswordValidator());
        $result = $this->filtre->execute($data);

        $this->assertTrue($result['password'], "password 'MyPassword123!' should be valid");
    }
    public function testInvalidPassword(): void {
        $data = [
            'password' => 'invalidPassword'
        ];
        $this->filtre->addValidator('password', new PasswordValidator());
        $result = $this->filtre->execute($data);

        $this->assertFalse($result['password'], "password 'invalidPassword' should be invalid");
    }

    // --- date de naissance ---
    public function testValidDateNaissance() : void {
        $data = [
            'dateNaissance' => '2008-06-15'
        ];
        $this->filtre->addValidator('dateNaissance', new DateNaissanceValidator());
        $result = $this->filtre->execute($data);

        $this->assertTrue($result['dateNaissance'], "dateNaissance should be valid");
    }

    public function testInvalidDateNaissance() : void {
        $data = [
            'dateNaissance' => '15/06/2008'
        ];
        $this->filtre->addValidator('dateNaissance', new DateNaissanceValidator());
        $result = $this->filtre->execute($data);

        $this->assertFalse($result['dateNaissance'], "dateNaissance should be valid");
    }

    // --- grade ---
    public function testValidGrade() : void {
        $data = [
            'grade' => 'AC'
        ];
        $this->filtre->addValidator('grade', new GradeValidator());
        $result = $this->filtre->execute($data);

        $this->assertTrue($result['grade'], "grade should be valid");
    }

    public function testInvalidGrade() : void {
        $data = [
            'grade' => 'XX'
        ];
        $this->filtre->addValidator('grade', new GradeValidator());
        $result = $this->filtre->execute($data);

        $this->assertFalse($result['grade'], "grade should be invalid");
    }

    // --- mail ---
    public function testValidEmail() : void {
        $data = [
            'email' => 'prenom.nom@test.fr'
        ];
        $this->filtre->addValidator('email', new MailValidator());
        $result = $this->filtre->execute($data);

        $this->assertTrue($result['email'], "email should be valid");
    }

    public function testInvalidEmail() : void {
        $data = [
            'email' => 'invalidEmail'
        ];
        $this->filtre->addValidator('email', new MailValidator());
        $result = $this->filtre->execute($data);
        $this->assertFalse($result['email'], "email should be invalid");
    }

    // --- matricule ---
    public function testValidMatricule() : void {
        $data = [
            'matricule' => 'P000107'
        ];
        $this->filtre->addValidator('matricule', new MatriculeValidator());
        $result = $this->filtre->execute($data);
        $this->assertTrue($result['matricule'], "matricule should be valid");
    }

    public function testInvalidMatricule() : void {
        $data = [
            'matricule' => 'invalidMatricule'
        ];
        $this->filtre->addValidator('matricule', new MatriculeValidator());
        $result = $this->filtre->execute($data);
        $this->assertFalse($result['matricule'], "matricule should be invalid");
    }

    // --- name ---
    public function testValidName() : void {
        $data = [
            'name' => 'Clément'
        ];
        $this->filtre->addValidator('name', new NameValidator());
        $result = $this->filtre->execute($data);
        $this->assertTrue($result['name'], "name should be valid");
    }

    public function testInvalidName() : void {
        $data = [
            'name' => 'Jean%Pierre'
        ];
        $this->filtre->addValidator('name', new NameValidator());
        $result = $this->filtre->execute($data);
        $this->assertFalse($result['name'], "name should be invalid");
    }

    public function teardown() : void {
        fwrite(STDOUT, __METHOD__ . "\nCleaning up after test...\n");
        parent::teardown();
    }

    public static function tearDownAfterClass() : void {
        fwrite(STDOUT, __METHOD__ . "\nDONE!\n");
    }

}
